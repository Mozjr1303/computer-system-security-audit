"""Professional 14-Section PDF Security Audit Report Generator using ReportLab."""
from datetime import datetime, timezone
from pathlib import Path
from typing import List
from xml.sax.saxutils import escape

from reportlab.graphics.charts.barcharts import HorizontalBarChart
from reportlab.graphics.shapes import Drawing, Rect, String
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.schemas.audit_schemas import AuditCheckResult, FullAuditResultSchema

# Brand colors
NAVY_DARK = colors.HexColor("#0B1120")
SLATE_HEADER = colors.HexColor("#1E293B")
ACCENT_BLUE = colors.HexColor("#2563EB")
PASS_GREEN = colors.HexColor("#059669")
WARN_AMBER = colors.HexColor("#D97706")
FAIL_RED = colors.HexColor("#DC2626")
NA_GRAY = colors.HexColor("#64748B")
ROW_ALT = colors.HexColor("#F8FAFC")
BORDER_GRAY = colors.HexColor("#CBD5E1")


def _safe(text: object) -> str:
    """Escape XML special characters for ReportLab Paragraph rendering."""
    return escape(str(text if text is not None else ""))


def _status_color(status: str):
    s = status.upper()
    if s == "PASS":
        return PASS_GREEN
    if s == "FAIL":
        return FAIL_RED
    if s == "WARNING":
        return WARN_AMBER
    return NA_GRAY


def _draw_page_header_footer(canvas, doc):
    """Draw professional running header and page number footer on every PDF page."""
    canvas.saveState()
    width, height = A4

    # Top header bar
    canvas.setFillColor(NAVY_DARK)
    canvas.rect(0, height - 12 * mm, width, 12 * mm, stroke=0, fill=1)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 8.5)
    canvas.drawString(15 * mm, height - 7.5 * mm, "WinSecAudit | Windows Host Security Audit Report")
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(width - 15 * mm, height - 7.5 * mm, "CONFIDENTIAL - UNIVERSITY CYBERSECURITY PROJECT")

    # Bottom footer
    canvas.setStrokeColor(BORDER_GRAY)
    canvas.line(15 * mm, 12 * mm, width - 15 * mm, 12 * mm)
    canvas.setFillColor(NA_GRAY)
    canvas.setFont("Helvetica", 8)
    canvas.drawString(
        15 * mm,
        7.5 * mm,
        f"Generated by WinSecAudit v1.0 (Read-Only Host Posture Assessment Engine)",
    )
    canvas.drawRightString(width - 15 * mm, 7.5 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _build_score_chart(audit: FullAuditResultSchema) -> Drawing:
    """Create a vector Horizontal Bar Chart comparing earned vs. max category points."""
    d = Drawing(460, 145)
    chart = HorizontalBarChart()
    chart.x = 115
    chart.y = 20
    chart.height = 105
    chart.width = 310

    cats = list(audit.score.categories.values())
    earned_series = [c.earned_points for c in cats]
    max_series = [c.max_points for c in cats]
    labels = [c.category_label for c in cats]

    chart.data = [earned_series, max_series]
    chart.categoryAxis.categoryNames = labels
    chart.categoryAxis.labels.fontName = "Helvetica-Bold"
    chart.categoryAxis.labels.fontSize = 8
    chart.valueAxis.valueMin = 0
    chart.valueAxis.valueMax = 25
    chart.valueAxis.valueStep = 5
    chart.valueAxis.labels.fontSize = 8

    chart.bars[0].fillColor = ACCENT_BLUE
    chart.bars[1].fillColor = colors.HexColor("#CBD5E1")
    d.add(chart)

    # Legend labels
    d.add(Rect(115, 132, 8, 8, fillColor=ACCENT_BLUE, strokeColor=None))
    d.add(String(127, 133, "Earned Points", fontName="Helvetica", fontSize=8, fillColor=NAVY_DARK))
    d.add(Rect(205, 132, 8, 8, fillColor=colors.HexColor("#CBD5E1"), strokeColor=None))
    d.add(String(217, 133, "Maximum Allocation", fontName="Helvetica", fontSize=8, fillColor=NAVY_DARK))
    return d


def generate_audit_pdf_report(
    audit: FullAuditResultSchema, output_dir: Path
) -> Path:
    """Generate a complete 14-section PDF security audit report from real scan results."""
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_host = "".join(
        c if c.isalnum() or c in ("-", "_") else "_"
        for c in audit.system_info.hostname
    )
    filename = f"WinSecAudit_Report_{safe_host}_{audit.audit_id}.pdf"
    pdf_path = output_dir / filename

    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=A4,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"Security Audit Report - {audit.system_info.hostname}",
        author="WinSecAudit Engine",
    )

    base_styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=base_styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=NAVY_DARK,
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=base_styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=14,
        textColor=ACCENT_BLUE,
        spaceAfter=12,
    )
    h1_style = ParagraphStyle(
        "SectionH1",
        parent=base_styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=NAVY_DARK,
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "BodyTextCustom",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#1E293B"),
        spaceAfter=6,
    )
    cell_style = ParagraphStyle(
        "TableCell",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#0F172A"),
    )
    cell_bold = ParagraphStyle(
        "TableCellBold",
        parent=cell_style,
        fontName="Helvetica-Bold",
    )
    cell_header = ParagraphStyle(
        "TableCellHeader",
        parent=cell_style,
        fontName="Helvetica-Bold",
        textColor=colors.white,
    )

    story = []

    # =========================================================================
    # SECTION 1: PROJECT TITLE & BANNER
    # =========================================================================
    story.append(Paragraph("1. SECURITY AUDIT OF A COMPUTER SYSTEM", subtitle_style))
    story.append(
        Paragraph(
            f"Windows Host Security Posture &amp; Compliance Report: {_safe(audit.system_info.hostname)}",
            title_style,
        )
    )
    story.append(
        Paragraph(
            "Comprehensive Read-Only Assessment of User Accounts, System Updates, File Permissions, Running Services, and Security Configurations.",
            body_style,
        )
    )
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 2, 3 & 4: COMPUTER INFO, OS DETAILS, AND AUDIT DATE/TIME
    # =========================================================================
    story.append(
        Paragraph(
            "2–4. Target Computer Information, Operating System Details &amp; Audit Metadata",
            h1_style,
        )
    )
    sys = audit.system_info
    meta_rows = [
        [
            Paragraph("<b>2. Computer Information</b>", cell_header),
            Paragraph("<b>Value</b>", cell_header),
            Paragraph("<b>3. OS &amp; 4. Audit Details</b>", cell_header),
            Paragraph("<b>Value</b>", cell_header),
        ],
        [
            Paragraph("Hostname", cell_bold),
            Paragraph(_safe(sys.hostname), cell_style),
            Paragraph("Operating System", cell_bold),
            Paragraph(_safe(sys.os_name), cell_style),
        ],
        [
            Paragraph("Manufacturer / Model", cell_bold),
            Paragraph(_safe(f"{sys.manufacturer} {sys.model}"), cell_style),
            Paragraph("OS Version &amp; Build", cell_bold),
            Paragraph(_safe(f"{sys.os_version} (Build {sys.os_build})"), cell_style),
        ],
        [
            Paragraph("Processor (CPU)", cell_bold),
            Paragraph(_safe(f"{sys.cpu_Model} ({sys.cpu_cores} Logical Cores)"), cell_style),
            Paragraph("OS Architecture", cell_bold),
            Paragraph(_safe(sys.architecture), cell_style),
        ],
        [
            Paragraph("Installed Memory (RAM)", cell_bold),
            Paragraph(_safe(f"{sys.ram_total_gb} GB"), cell_style),
            Paragraph("PowerShell Version", cell_bold),
            Paragraph(_safe(sys.powershell_version), cell_style),
        ],
        [
            Paragraph("Domain / Workgroup", cell_bold),
            Paragraph(_safe(sys.domain_or_workgroup), cell_style),
            Paragraph("Audit Session ID", cell_bold),
            Paragraph(_safe(audit.audit_id), cell_style),
        ],
        [
            Paragraph("Audited User Context", cell_bold),
            Paragraph(
                _safe(
                    f"{sys.current_user} ({'Administrator' if sys.is_admin else 'Standard User'})"
                ),
                cell_style,
            ),
            Paragraph("Audit Date &amp; Time (UTC)", cell_bold),
            Paragraph(_safe(f"{audit.completed_at[:19].replace('T', ' ')} ({audit.duration_seconds}s)"), cell_style),
        ],
    ]
    meta_table = Table(meta_rows, colWidths=[38 * mm, 52 * mm, 42 * mm, 48 * mm])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), SLATE_HEADER),
                ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ROW_ALT]),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(meta_table)
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 5 & 6: EXECUTIVE SUMMARY & OVERALL SECURITY SCORE
    # =========================================================================
    story.append(Paragraph("5. Executive Summary", h1_style))
    story.append(Paragraph(_safe(audit.score.executive_summary), body_style))

    story.append(Paragraph("6. Overall Security Score &amp; Category Breakdown", h1_style))
    score_val = audit.score.overall_score
    score_banner = Table(
        [
            [
                Paragraph(
                    f"<font size='18'><b>OVERALL SECURITY SCORE: {score_val} / 100</b></font><br/>"
                    f"<font size='10'>Risk Posture Rating: <b>{_safe(audit.score.risk_rating)}</b></font>",
                    ParagraphStyle(
                        "ScoreBanner",
                        parent=body_style,
                        textColor=colors.white,
                        leading=18,
                    ),
                ),
                Paragraph(
                    f"<b>Total Checks:</b> {audit.score.total_checks}<br/>"
                    f"<b>Passed:</b> {audit.score.passed_checks} | <b>Failed:</b> {audit.score.failed_checks}<br/>"
                    f"<b>Warnings:</b> {audit.score.warning_checks} | <b>Not Assessed:</b> {audit.score.not_assessed_checks}<br/>"
                    f"<b>Critical Findings:</b> {audit.score.critical_findings_count} | <b>High Findings:</b> {audit.score.high_findings_count}",
                    ParagraphStyle(
                        "ScoreStats",
                        parent=cell_style,
                        textColor=colors.white,
                        leading=12,
                    ),
                ),
            ]
        ],
        colWidths=[105 * mm, 75 * mm],
    )
    score_banner.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), NAVY_DARK),
                ("BOX", (0, 0), (-1, -1), 1, ACCENT_BLUE),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ]
        )
    )
    story.append(score_banner)
    story.append(Spacer(1, 3 * mm))

    cat_rows = [
        [
            Paragraph("<b>Audit Category</b>", cell_header),
            Paragraph("<b>Earned / Max</b>", cell_header),
            Paragraph("<b>Score %</b>", cell_header),
            Paragraph("<b>Passed</b>", cell_header),
            Paragraph("<b>Failed</b>", cell_header),
            Paragraph("<b>Warnings</b>", cell_header),
            Paragraph("<b>Not Assessed</b>", cell_header),
        ]
    ]
    for c in audit.score.categories.values():
        cat_rows.append(
            [
                Paragraph(_safe(c.category_label), cell_bold),
                Paragraph(f"{c.earned_points} / {c.max_points}", cell_style),
                Paragraph(f"{c.percentage}%", cell_style),
                Paragraph(str(c.passed_checks), cell_style),
                Paragraph(str(c.failed_checks), cell_style),
                Paragraph(str(c.warning_checks), cell_style),
                Paragraph(str(c.not_assessed_checks), cell_style),
            ]
        )
    cat_table = Table(
        cat_rows,
        colWidths=[48 * mm, 26 * mm, 22 * mm, 20 * mm, 20 * mm, 22 * mm, 22 * mm],
    )
    cat_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), SLATE_HEADER),
                ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ROW_ALT]),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]
        )
    )
    story.append(cat_table)
    story.append(Spacer(1, 3 * mm))
    story.append(_build_score_chart(audit))
    story.append(Paragraph(f"<i>Methodology: {_safe(audit.score.methodology_notes)}</i>", cell_style))

    # Helper to render checks table for each module
    def render_module_checks_table(checks: List[AuditCheckResult]):
        rows = [
            [
                Paragraph("<b>ID &amp; Check</b>", cell_header),
                Paragraph("<b>Status / Severity</b>", cell_header),
                Paragraph("<b>Evidence &amp; Explanation</b>", cell_header),
                Paragraph("<b>Recommended Remediation</b>", cell_header),
            ]
        ]
        for chk in checks:
            st_col = _status_color(chk.status.value)
            rows.append(
                [
                    Paragraph(
                        f"<b>{_safe(chk.check_id)}</b><br/>{_safe(chk.title)}<br/>"
                        f"<font size='7' color='#475569'>[{_safe(chk.finding_type.value)}]</font>",
                        cell_style,
                    ),
                    Paragraph(
                        f"<font color='{st_col.hexval()}'><b>{_safe(chk.status.value)}</b></font><br/>"
                        f"Severity: <b>{_safe(chk.severity.value)}</b>",
                        cell_style,
                    ),
                    Paragraph(
                        f"<b>Evidence:</b> <font name='Courier' size='7.5'>{_safe(chk.evidence)}</font><br/>"
                        f"<b>Impact:</b> {_safe(chk.explanation)}",
                        cell_style,
                    ),
                    Paragraph(_safe(chk.remediation), cell_style),
                ]
            )
        t = Table(rows, colWidths=[36 * mm, 28 * mm, 68 * mm, 48 * mm], repeatRows=1)
        t.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), SLATE_HEADER),
                    ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ROW_ALT]),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        return t

    story.append(PageBreak())

    # =========================================================================
    # SECTION 7: USER ACCOUNT FINDINGS
    # =========================================================================
    story.append(Paragraph("7. User Account Audit Findings (Module B)", h1_style))
    umod = audit.users_module
    story.append(
        Paragraph(
            f"Inspected <b>{umod.total_accounts}</b> local user accounts ({umod.enabled_accounts} Enabled, {umod.admin_accounts} Administrator). "
            f"Minimum Password Length: <b>{umod.password_policy.min_password_length} chars</b> | "
            f"Lockout Threshold: <b>{_safe(umod.password_policy.lockout_threshold)}</b>.",
            body_style,
        )
    )
    story.append(render_module_checks_table(umod.checks))
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 8: SYSTEM UPDATE FINDINGS
    # =========================================================================
    story.append(Paragraph("8. System Update Audit Findings (Module C)", h1_style))
    upmod = audit.updates_module
    story.append(
        Paragraph(
            f"OS Build: <b>{_safe(upmod.os_caption)} (Build {_safe(upmod.os_build)})</b> | "
            f"Installed Hotfixes: <b>{len(upmod.installed_updates)}</b> | "
            f"Latest Update Date: <b>{_safe(upmod.last_update_date or 'N/A')}</b> ({upmod.days_since_last_update} days ago).",
            body_style,
        )
    )
    story.append(render_module_checks_table(upmod.checks))
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 9: FILE PERMISSION FINDINGS
    # =========================================================================
    story.append(Paragraph("9. File and Directory Permission Findings (Module D)", h1_style))
    pmod = audit.permissions_module
    story.append(
        Paragraph(
            f"Inspected NTFS Access Control Lists across <b>{pmod.inspected_paths_count}</b> critical system directories "
            f"({len(pmod.entries)} ACEs evaluated; <b>{pmod.risky_permissions_count}</b> risky ACEs flagged).",
            body_style,
        )
    )
    story.append(render_module_checks_table(pmod.checks))

    story.append(PageBreak())

    # =========================================================================
    # SECTION 10: RUNNING SERVICES FINDINGS
    # =========================================================================
    story.append(Paragraph("10. Running Services Audit Findings (Module E)", h1_style))
    smod = audit.services_module
    story.append(
        Paragraph(
            f"Total Services: <b>{smod.total_services}</b> | Running: <b>{smod.running_services}</b> | "
            f"Running as LocalSystem: <b>{smod.elevated_running_services}</b> | "
            f"Flagged Risky Services: <b>{smod.risky_services_count}</b>.",
            body_style,
        )
    )
    story.append(render_module_checks_table(smod.checks))
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 11: SECURITY CONFIGURATION FINDINGS
    # =========================================================================
    story.append(Paragraph("11. Security Configuration Audit Findings (Module F)", h1_style))
    secmod = audit.security_module
    story.append(
        Paragraph(
            f"Evaluated <b>{len(secmod.controls)}</b> core Windows security controls across Defender, Firewall, UAC, Remote Desktop, Secure Boot, BitLocker, and SMBv1.",
            body_style,
        )
    )
    story.append(render_module_checks_table(secmod.checks))
    story.append(Spacer(1, 4 * mm))

    # =========================================================================
    # SECTION 12 & 13: IDENTIFIED VULNERABILITIES & REMEDIATION ROADMAP
    # =========================================================================
    story.append(
        Paragraph("12 &amp; 13. Identified Weaknesses &amp; Prioritized Remediation Roadmap", h1_style)
    )
    actionable = [
        c for c in audit.all_checks if c.status.value in ("FAIL", "WARNING")
    ]
    if not actionable:
        story.append(
            Paragraph(
                "No failed or warning checks were identified during this assessment.",
                body_style,
            )
        )
    else:
        rem_rows = [
            [
                Paragraph("<b>Priority / Check ID</b>", cell_header),
                Paragraph("<b>Classification</b>", cell_header),
                Paragraph("<b>Identified Weakness / Vulnerability</b>", cell_header),
                Paragraph("<b>Actionable Remediation Step</b>", cell_header),
            ]
        ]
        for chk in actionable:
            rem_rows.append(
                [
                    Paragraph(
                        f"<b>{_safe(chk.severity.value)}</b><br/>{_safe(chk.check_id)} ({_safe(chk.status.value)})",
                        cell_style,
                    ),
                    Paragraph(_safe(chk.finding_type.value), cell_style),
                    Paragraph(f"<b>{_safe(chk.title)}:</b> {_safe(chk.evidence)}", cell_style),
                    Paragraph(_safe(chk.remediation), cell_style),
                ]
            )
        rem_table = Table(rem_rows, colWidths=[30 * mm, 32 * mm, 60 * mm, 58 * mm], repeatRows=1)
        rem_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), FAIL_RED),
                    ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ROW_ALT]),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ]
            )
        )
        story.append(rem_table)

    story.append(Spacer(1, 5 * mm))

    # =========================================================================
    # SECTION 14: FINAL ASSESSMENT
    # =========================================================================
    story.append(KeepTogether([
        Paragraph("14. Final Security Posture Assessment", h1_style),
        Paragraph(
            f"Based on the automated read-only inspection of <b>{_safe(sys.hostname)}</b> running "
            f"<b>{_safe(sys.os_name)} (Build {_safe(sys.os_build)})</b>, the host achieved an overall security posture score of "
            f"<b>{audit.score.overall_score} / 100 ({_safe(audit.score.risk_rating)})</b>. "
            f"Core platform defenses including Windows Defender Real-Time Protection, Tamper Protection, Windows Firewall across all three profiles, "
            f"UAC Secure Desktop, UEFI Secure Boot, SMBv1 deprecation, and NTFS system directory permissions were verified as active and compliant. "
            f"Addressing the <b>{audit.score.failed_checks} failed check(s)</b> and <b>{audit.score.warning_checks} warning(s)</b> listed in Section 12–13 "
            f"will bring the workstation into full alignment with security hardening benchmarks.",
            body_style,
        ),
    ]))

    doc.build(
        story,
        onFirstPage=_draw_page_header_footer,
        onLaterPages=_draw_page_header_footer,
    )
    return pdf_path
